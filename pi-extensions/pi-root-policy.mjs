const GENERATED_NOTE = "Generated by pi-extensions/pi-root-policy.mjs; do not edit.";
const root = dirname(fileURLToPath(import.meta.url));
const repo = dirname(root);

function markerLiteral(indent = "\t") {
	return PROJECT_MARKER_DIRS.map((marker) => `${indent}${JSON.stringify(marker)},`).join("\n");
}

export function typescriptSource() {
	return `// ${GENERATED_NOTE}
import { statSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, posix, resolve, win32 } from "node:path";

export type PiPathPlatform = "posix" | "win32";

export const PI_PROJECT_MARKER_DIRS = [
${markerLiteral()}
] as const;

function platformPath(platform: PiPathPlatform) {
	return platform === "win32" ? win32 : posix;
}

export function piRootIsAbsolute(value: string, platform: PiPathPlatform): boolean {
	if (platform === "posix") return value.startsWith("/");
	if (/^[A-Za-z]:[\\\\/]/.test(value)) return true;
	return /^(?:\\\\\\\\|\\/\\/)[^\\\\/]+[\\\\/][^\\\\/]+(?:[\\\\/]|$)/.test(value);
}

function expandTilde(value: string, home: string, platform: PiPathPlatform): string {
	const paths = platformPath(platform);
	if (value === "~") return home;
	if (value.startsWith("~/")) return paths.join(home, value.slice(2));
	return value;
}

export function piGlobalRoot(
	value: string | undefined = process.env.PI_CODING_AGENT_DIR,
	home: string = homedir(),
	platform: PiPathPlatform = process.platform === "win32" ? "win32" : "posix",
): string {
	const paths = platformPath(platform);
	const configured = value?.trim();
	if (!configured) return paths.resolve(home, ".pi", "agent");
	const expanded = expandTilde(configured, home, platform);
	return piRootIsAbsolute(expanded, platform) ? paths.resolve(expanded) : paths.resolve(home, ".pi", "agent");
}

function isDirectory(path: string): boolean {
	try { return statSync(path).isDirectory(); } catch { return false; }
}

function isFile(path: string): boolean {
	try { return statSync(path).isFile(); } catch { return false; }
}

export function piProjectRoot(cwd: string, home: string = homedir()): string | undefined {
	let current = resolve(cwd);
	const stop = resolve(home);
	while (true) {
		if (isFile(join(current, ".kendex-lock.json"))) return current;
		if (current !== stop && PI_PROJECT_MARKER_DIRS.some((marker) => isDirectory(join(current, marker)))) return current;
		const parent = dirname(current);
		if (parent === current) return undefined;
		current = parent;
	}
}
`;
}

export function installSource() {
	return `// ${GENERATED_NOTE}
import { homedir } from "node:os";
import { posix, win32 } from "node:path";

function isAbsolute(value, platform) {
	if (platform === "posix") return value.startsWith("/");
	if (/^[A-Za-z]:[\\\\/]/.test(value)) return true;
	return /^(?:\\\\\\\\|\\/\\/)[^\\\\/]+[\\\\/][^\\\\/]+(?:[\\\\/]|$)/.test(value);
}

export function piGlobalRoot(
	value = process.env.PI_CODING_AGENT_DIR,
	home = homedir(),
	platform = process.platform === "win32" ? "win32" : "posix",
) {
	const paths = platform === "win32" ? win32 : posix;
	const configured = value?.trim();
	if (!configured) return paths.resolve(home, ".pi", "agent");
	const expanded = configured === "~" ? home : configured.startsWith("~/") ? paths.join(home, configured.slice(2)) : configured;
	return isAbsolute(expanded, platform) ? paths.resolve(expanded) : paths.resolve(home, ".pi", "agent");
}
`;
}

function rustMarkers() {
	return `// pi-root-policy:project-markers begin
const MARKER_DIRS: [&str; ${PROJECT_MARKER_DIRS.length}] = [
${markerLiteral("    ")}
];
// pi-root-policy:project-markers end`;
}

function rustRootPolicy() {
	const cases = ABSOLUTE_CASES.map(([value, posixExpected, windowsExpected]) =>
		`    (${JSON.stringify(value)}, ${posixExpected}, ${windowsExpected}),`).join("\n");
	return `// pi-root-policy:global-root begin
fn pi_root_is_absolute_for(value: &str, windows: bool) -> bool {
    if !windows {
        return value.starts_with('/');
    }
    let bytes = value.as_bytes();
    if bytes.len() >= 3
        && bytes[0].is_ascii_alphabetic()
        && bytes[1] == b':'
        && matches!(bytes[2], b'\\\\' | b'/')
    {
        return true;
    }
    let Some(rest) = value
        .strip_prefix(r"\\\\")
        .or_else(|| value.strip_prefix("//"))
    else {
        return false;
    };
    let mut parts = rest.split(['\\\\', '/']);
    matches!((parts.next(), parts.next()), (Some(server), Some(share)) if !server.is_empty() && !share.is_empty())
}

fn pi_global_root(env: &Env) -> PathBuf {
    let default = || env.home.join(".pi/agent");
    let Some(dir) = env
        .var("PI_CODING_AGENT_DIR")
        .map(str::trim)
        .filter(|dir| !dir.is_empty())
    else {
        return default();
    };
    let root = crate::paths::expand_tilde(&env.home, dir);
    if pi_root_is_absolute_for(&root.to_string_lossy(), cfg!(windows)) {
        root
    } else {
        default()
    }
}

#[cfg(test)]
const PI_ROOT_ABSOLUTE_CASES: &[(&str, bool, bool)] = &[
${cases}
];
// pi-root-policy:global-root end`;
}

function replaceBlock(text, begin, end, replacement, path) {
	const start = text.indexOf(begin);
	const finish = text.indexOf(end);
	if (start < 0 || finish < start) throw new Error(`${path}: missing generated block ${begin}`);
	const after = finish + end.length;
	return `${text.slice(0, start)}${replacement}${text.slice(after)}`;
}

function expectedFiles() {
	return [
		...TYPESCRIPT_OUTPUTS.map((path) => [join(root, path), typescriptSource()]),
		...INSTALL_OUTPUTS.map((path) => [join(root, path), installSource()]),
	];
}

function rustFiles() {
	return [
		[join(repo, "crates/core/src/discover.rs"), "// pi-root-policy:project-markers begin", "// pi-root-policy:project-markers end", rustMarkers()],
		[join(repo, "crates/core/src/harness/pi.rs"), "// pi-root-policy:global-root begin", "// pi-root-policy:global-root end", rustRootPolicy()],
	];
}

export function writeOutputs() {
	for (const [path, content] of expectedFiles()) writeFileSync(path, content);
	for (const [path, begin, end, replacement] of rustFiles()) {
		writeFileSync(path, replaceBlock(readFileSync(path, "utf8"), begin, end, replacement, path));
	}
}

export function checkOutputs() {
	const stale = [];
	for (const [path, expected] of expectedFiles()) {
		if (!existsSync(path) || readFileSync(path, "utf8") !== expected) stale.push(path);
	}
	for (const [path, begin, end, replacement] of rustFiles()) {
		const current = readFileSync(path, "utf8");
		if (replaceBlock(current, begin, end, replacement, path) !== current) stale.push(path);
	}
	return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const action = process.argv[2];
	if (action === "--write") writeOutputs();
	else if (action === "--check") {
		const stale = checkOutputs();
		if (stale.length) {
			console.error(`pi-root-policy: stale outputs:\n${stale.join("\n")}`);
			process.exit(1);
		}
	} else {
		console.error("usage: node pi-extensions/pi-root-policy.mjs --write|--check");
		process.exit(2);
	}
}
