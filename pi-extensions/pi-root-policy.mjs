#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const OUTPUTS = [
	"pi-agents-tmux/scripts/pi-root.js", "pi-background-tasks/scripts/pi-root.js", "pi-caveman/extensions/pi-root.js",
	"pi-codex-minimal-tools/src/pi-root.js", "pi-extension-manager/extensions/manager/pi-root.js", "pi-hooks/extensions/pi-root.js",
	"pi-output-policy/extensions/pi-root.js", "pi-prompt-stash/extensions/pi-root.js", "pi-qol/extensions/qol/pi-root.js",
	"pi-questions/scripts/pi-root.js", "pi-session-bridge/scripts/pi-root.js", "pi-session-manager/extensions/pi-root.js",
	"pi-skills-manager/extensions/skills-manager/pi-root.js", "pi-task-panel/scripts/pi-root.js",
	"pi-tool-renderer/extensions/tool-renderer/pi-root.js", "pi-web-tools/scripts/pi-root.js",
];
const DECLARATIONS = new Set(OUTPUTS.filter((path) => !path.includes("/scripts/") || path.startsWith("pi-web-tools/")));
export const ABSOLUTE_CASES = [["/root", true, false], ["C:/root", false, true], ["C:\\root", false, true], ["//server/share", true, true], ["\\\\server\\share", false, true], ["\\root", false, false], ["relative/root", false, false]];
const root = dirname(fileURLToPath(import.meta.url));
const note = "Generated by pi-extensions/pi-root-policy.mjs; do not edit.";
const js = `// ${note}
import { homedir } from "node:os"; import { posix, win32 } from "node:path";
export function piGlobalRoot(value=process.env.PI_CODING_AGENT_DIR, home=homedir(), platform=process.platform === "win32" ? "win32" : "posix") {
	const p=platform === "win32" ? win32 : posix, raw=value?.trim(), path=raw === "~" ? home : raw?.startsWith("~/") ? p.join(home, raw.slice(2)) : raw, absolute=platform === "win32" ? (/^[A-Za-z]:[\\\\/]/.test(path ?? "") || /^(?:\\\\\\\\|\\/\\/)[^\\\\/]+[\\\\/][^\\\\/]+(?:[\\\\/]|$)/.test(path ?? "")) : path?.startsWith("/");
	return absolute ? p.resolve(path) : p.resolve(home, ".pi", "agent"); }
`;
const declaration = `export function piGlobalRoot(value?: string, home?: string, platform?: "posix" | "win32"): string;\n`;
const claude = `// pi-root-policy:claude begin
function piGlobalRoot() { const home=homedir(), raw=process.env.PI_CODING_AGENT_DIR?.trim(), path=raw === "~" ? home : raw?.startsWith("~/") ? join(home, raw.slice(2)) : raw, absolute=process.platform === "win32" ? (/^[A-Za-z]:[\\\\/]/.test(path ?? "") || /^(?:\\\\\\\\|\\/\\/)[^\\\\/]+[\\\\/][^\\\\/]+(?:[\\\\/]|$)/.test(path ?? "")) : path?.startsWith("/"); return absolute ? resolve(path) : resolve(home, ".pi", "agent"); }
// pi-root-policy:claude end`;
const bundle = `function piUserDir() {
  const home = homedir(), raw = process.env.PI_CODING_AGENT_DIR?.trim(), path = raw === "~" ? home : raw?.startsWith("~/") ? join3(home, raw.slice(2)) : raw, absolute = process.platform === "win32" ? /^[A-Za-z]:[\\\\/]/.test(path ?? "") || /^(?:\\\\\\\\|\\/\\/)[^\\\\/]+[\\\\/][^\\\\/]+(?:[\\\\/]|$)/.test(path ?? "") : path?.startsWith("/");
  return absolute ? resolve2(path) : resolve2(home, ".pi", "agent");
}`;
const rust = `// pi-root-policy:global-root begin
fn pi_root_is_absolute_for(value: &str, windows: bool) -> bool {
    if !windows {
        return value.starts_with('/');
    }
    let bytes = value.as_bytes();
    if bytes.len() >= 3
        && bytes[0].is_ascii_alphabetic()
        && bytes[1] == b':'
        && matches!(bytes[2], b'\\\\' | b'/')
    {
        return true;
    }
    let Some(rest) = value
        .strip_prefix(r"\\\\")
        .or_else(|| value.strip_prefix("//"))
    else {
        return false;
    };
    let mut parts = rest.split(['\\\\', '/']);
    matches!((parts.next(), parts.next()), (Some(server), Some(share)) if !server.is_empty() && !share.is_empty())
}
fn pi_global_root(env: &Env) -> PathBuf {
    let default = || env.home.join(".pi/agent");
    let Some(dir) = env
        .var("PI_CODING_AGENT_DIR")
        .map(str::trim)
        .filter(|dir| !dir.is_empty())
    else {
        return default();
    };
    let root = crate::paths::expand_tilde(&env.home, dir);
    if pi_root_is_absolute_for(&root.to_string_lossy(), cfg!(windows)) {
        root
    } else {
        default()
    }
}
#[cfg(test)]
const PI_ROOT_ABSOLUTE_CASES: &[(&str, bool, bool)] = &[
    ("/root", true, false),
    ("C:/root", false, true),
    ("C:\\\\root", false, true),
    ("//server/share", true, true),
    ("\\\\\\\\server\\\\share", false, true),
    ("\\\\root", false, false),
    ("relative/root", false, false),
];
// pi-root-policy:global-root end`;
const rustPath = join(root, "..", "crates/core/src/harness/pi.rs");
const claudePath = join(root, "pi-claude-bridge/src/config.ts");
const bundlePath = join(root, "pi-claude-bridge/bundle/index.js");
function replace(text, begin, end, value) { return text.replace(new RegExp(`${begin}[\\s\\S]*?${end}`), value); }
function replaceRust(text) { return replace(text, "// pi-root-policy:global-root begin", "// pi-root-policy:global-root end", rust); }
function rustBlock(text) { return text.match(/\/\/ pi-root-policy:global-root begin[\s\S]*?\/\/ pi-root-policy:global-root end/)?.[0]; }
function normalized(text) { return text?.replace(/\s+/g, "").replace(/,\]/g, "]"); }
function replaceClaude(text) { return replace(text, "// pi-root-policy:claude begin", "// pi-root-policy:claude end", claude); }
function replaceBundle(text) { return text.replace(/function piUserDir\(\) \{[\s\S]*?\n\}/, bundle); }
export function writeOutputs() {
	for (const path of OUTPUTS) { writeFileSync(join(root, path), js); if (DECLARATIONS.has(path)) writeFileSync(join(root, path.replace(/\.js$/, ".d.ts")), declaration); }
	writeFileSync(rustPath, replaceRust(readFileSync(rustPath, "utf8")));
	writeFileSync(claudePath, replaceClaude(readFileSync(claudePath, "utf8")));
	writeFileSync(bundlePath, replaceBundle(readFileSync(bundlePath, "utf8")));
}
export function checkOutputs() {
	const stale=[];
	for (const path of OUTPUTS) for (const [file, expected] of [[path, js], ...(DECLARATIONS.has(path) ? [[path.replace(/\.js$/, ".d.ts"), declaration]] : [])]) { const at=join(root, file); if (!existsSync(at) || readFileSync(at, "utf8") !== expected) stale.push(at); }
	const current=readFileSync(rustPath, "utf8"); if (normalized(rustBlock(current)) !== normalized(rust)) stale.push(rustPath);
	const config=readFileSync(claudePath, "utf8"); if (replaceClaude(config) !== config) stale.push(claudePath);
	const bundled=readFileSync(bundlePath, "utf8"); if (replaceBundle(bundled) !== bundled) stale.push(bundlePath);
	return stale;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
	if (process.argv[2] === "--write") writeOutputs();
	else if (process.argv[2] === "--check") { const stale=checkOutputs(); if (stale.length) { console.error(`pi-root-policy: stale outputs:\n${stale.join("\n")}`); process.exit(1); } }
	else { console.error("usage: node pi-extensions/pi-root-policy.mjs --write|--check"); process.exit(2); }
}
