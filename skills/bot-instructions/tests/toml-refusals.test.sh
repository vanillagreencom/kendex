#!/usr/bin/env bash
# `toml-schema`'s content refusals. Each row here is one red control over a
# cell of `repo-toml.md` § The content refusals, which the generator reads as
# data and whose predicates are encoded once in `scripts/lib/refusals.py`. It
# is NOT a control per cell of that table: a row carries several predicates
# and only the combinations below are exercised, so
# `[bot-instructions.repo] name` is here for its marker refusal and not its
# others, and `[bot-instructions.tone] coderabbit` has no row at all. A row
# added to the table alone is proved to reach validation below. The schema's
# shape clauses are `toml-schema.test.sh`.
#
# Every control starts from a TOML with every `[bot-instructions.bots]` flag
# false, a legitimate state that renders nothing, and pins the
# `(<predicate> refusal, <row>)` suffix `refusals.apply` appends: a row
# carries several predicates, `apply` raises on the first to match, so a
# control that held only the validator's name passed whichever predicate was
# doing the work.

. "$(dirname "$0")/lib/harness.sh"

repo="$(bi_minimal_repo toml-refusals)"

# One record per mutation, read by `bi_toml_table`: `append` rows are the
# mutation under `$BI_MIN_HEAD`, `whole` rows the file entire. A setext
# heading, `Injected` over `===`, reaches `.github/copilot-instructions.md`
# and `.macroscope/correctness/doctrine.md` as an H1, which an ATX-only
# refusal does not see. A control character arrives through TOML's own
# escapes: the `\u0001` in the summary row parses cleanly and yields a
# literal byte, so the value is decoded by the time the refusal sees it.
# `read -d ''` rather than `$(cat <<'ROWS' ...)`: Bash 3.2 scans a
# here-document inside a command substitution for quotes, and a row carrying
# an odd number of double quotes runs its parse past the closing parenthesis.
IFS= read -r -d '' rows <<'ROWS'
a heading in [bot-instructions.repo] summary, indented, which is the wide predicate|whole|check|(heading refusal, [bot-instructions.repo] summary)
[bot-instructions]
schema = 1
[bot-instructions.repo]
name = "fixture"
summary = """
text
  ## forged
"""
END
a setext heading in [bot-instructions.repo] summary|whole|check|(heading refusal, [bot-instructions.repo] summary)
[bot-instructions]
schema = 1
[bot-instructions.repo]
name = "fixture"
summary = """
Injected
===
"""
END
a `---` line under text in [bot-instructions.repo] summary|whole|check|(heading refusal, [bot-instructions.repo] summary)
[bot-instructions]
schema = 1
[bot-instructions.repo]
name = "fixture"
summary = """
text
---
more
"""
END
the marker text in [bot-instructions.repo] summary|whole|check|(marker refusal, [bot-instructions.repo] summary)
[bot-instructions]
schema = 1
[bot-instructions.repo]
name = "fixture"
summary = "generated by bot-instructions is not a repo's to say"
END
a control character in [bot-instructions.repo] summary|whole|check|(control refusal, [bot-instructions.repo] summary)
[bot-instructions]
schema = 1
[bot-instructions.repo]
name = "fixture"
summary = "a\u0001b"
END
the marker text in [bot-instructions.repo] name|whole|check|(marker refusal, [bot-instructions.repo] name)
[bot-instructions]
schema = 1
[bot-instructions.repo]
name = "generated by bot-instructions"
summary = "A fixture repository."
END
a newline in [bot-instructions.repo] tracker, which no destination carries|whole|check|(single-line refusal, [bot-instructions.repo] tracker)
[bot-instructions]
schema = 1
[bot-instructions.repo]
name = "fixture"
summary = "A fixture repository."
tracker = """
KEN
1
"""
END
comment-close in an exclusion reason|append|check|(comment-close refusal, [[bot-instructions.exclusions.path]] reason)
[[bot-instructions.exclusions.path]]
glob = "a/**"
reason = "ends the comment --> and then some"
END
a newline in an exclusion reason|append|check|(single-line refusal, [[bot-instructions.exclusions.path]] reason)
[[bot-instructions.exclusions.path]]
glob = "a/**"
reason = """
two
lines
"""
END
a toml-delimiter in a [bot-instructions.doctrine.replace] value|append|check|(toml-delimiter refusal, [bot-instructions.doctrine.*] values)
[bot-instructions.doctrine.replace]
scope = "closes its own string \"\"\" then TOML"
END
a heading in a [bot-instructions.doctrine.append] value|append|check|(heading refusal, [bot-instructions.doctrine.*] values)
[bot-instructions.doctrine.append]
scope = """
text
# forged
"""
END
the marker text in a [[bot-instructions.surface]] instructions|append|check|(marker refusal, [[bot-instructions.surface]] instructions)
[bot-instructions.bots]
codex = true
copilot = true
[[bot-instructions.surface]]
name = "t"
globs = ["a/**"]
instructions = "generated by bot-instructions"
END
ROWS
bi_toml_table 'the content refusals' "$repo" "$rows"

# § Cross-file sets: the content-refusal table is the one statement of which
# input is under which refusal, so a row added there alone reaches
# validation. `code_review_path` has no row, and a value carrying the marker
# text fails its path class; under a copy whose table gives it a marker row,
# the same value is that row's refusal, which no hand-kept list could supply.
repo="$(bi_minimal_repo refusal-row-added)"
{ printf '%s' "$BI_MIN_HEAD"
  printf 'code_review_path = ".github/instructions/generated by bot-instructions.md"\n'
} > "$repo/kendex.toml"
expect_clause toml-schema 'must be non-empty and hold only [A-Za-z0-9._/-]' \
  'a code_review_path carrying the marker text, with no row of its own, fails its path class' \
  check --repo "$repo"
added="$(bi_mutant refusal-row-added schemas/repo-toml.md \
  '| `[bot-instructions.tone] coderabbit` | – | – | – | – | yes | – |
' '| `[bot-instructions.tone] coderabbit` | – | – | – | – | yes | – |
| `[bot-instructions.repo] code_review_path` | – | yes | – | – | – | – |
')" || exit 1
BI="$added" expect_clause toml-schema '(marker refusal, [bot-instructions.repo] code_review_path)' \
  'a row added to the content-refusal table alone refuses that input' \
  check --repo "$repo"

# The tables are read as data, so a defect in one is refused rather than read
# as a smaller set: a misspelt row label would otherwise drop every refusal of
# that input, a cell other than `yes` or a dash would drop that predicate, a
# role other than `review` or `not review` would silence `qodo-parity` for
# that verb, and a line before the blank that ends the table would otherwise
# end it there, dropping that row and every row under it. Each row is a copy of the package whose `schemas/repo-toml.md`
# carries one defect, `label~old~new~value` with `\n` for a newline in `new`,
# asserted as the `spec` refusal naming the value it acted on, over a manifest
# the running copy passes.
repo="$(bi_minimal_repo table-defects)"
printf '%s' "$BI_MIN_HEAD" > "$repo/kendex.toml"
expect_green 'the running copy reads its own tables, the pair for the rows below' \
  check --repo "$repo"
IFS= read -r -d '' rows <<'ROWS'
a content-refusal row label naming no string input~| `[bot-instructions.repo] tracker` |~| `[bot-instructions.repo] trackr` |~'[bot-instructions.repo] trackr'
a content-refusal cell neither yes nor a dash~| `[bot-instructions.tone] coderabbit` | – | – | – | – | yes | – |~| `[bot-instructions.tone] coderabbit` | – | – | – | – | Yes | – |~'Yes'
a content-refusal column naming no predicate~| Input string | heading |~| Input string | headline |~'headline'
a second table headed Input string~**Refusals, not escapes.**~| Input string | heading |\n|---|---|\n| x | yes |\n\n**Refusals, not escapes.**~'Input string'
a verb role neither review nor not review~| `/review` | Merge | review |~| `/review` | Merge | Review |~'Review'
a content-refusal row indented one space~| `[[bot-instructions.exclusions.path]] reason` |~ | `[[bot-instructions.exclusions.path]] reason` |~[[bot-instructions.exclusions.path]] reason` |
a content-refusal row without its leading pipe~| `[[bot-instructions.exclusions.path]] reason` |~`[[bot-instructions.exclusions.path]] reason` |~[[bot-instructions.exclusions.path]] reason` |
ROWS
n=0
while IFS= read -r row; do
  [ -n "$row" ] || continue
  IFS='~' read -r label old new value <<EOF
$row
EOF
  n=$((n + 1))
  mutant="$(bi_mutant "table-defect-$n" schemas/repo-toml.md "$old" "$(printf '%b' "$new")")" ||
    { printf 'fixture: %s\n' "$label" >&2; exit 1; }
  BI="$mutant" bi_run check --repo "$repo"
  got="$(bi_render)"
  if [ "$got" = 'rc=2 out=spec' ] && bi_carries "$value"; then
    ok "$label"
  else
    bad "$label" "want rc=2 out=spec naming $value; got $got: $(printf '%s' "$bi_out" | head -2 | tr '\n' ' ')"
  fi
done <<EOF
$rows
EOF
[ "$n" -gt 0 ] || { printf 'no table-defect row was asserted\n' >&2; exit 2; }

# The class holds three characters ABOVE C0, because a YAML reader breaks a
# line on all three: U+0085 NEL, U+2028 LINE SEPARATOR, U+2029 PARAGRAPH
# SEPARATOR. A `reason` carrying one is emitted as the comment above its
# entry, and the reader takes the rest as a `path_filters:` key whose first
# entry has no `!` — the allowlist state. Each is paired with the ordinary
# value it deviates from by that one character. Written as TOML escapes: a
# literal separator here would be invisible to a reader and to a diff.
repo="$(bi_minimal_repo line-separators)"
mkdir -p "$repo/a"
printf 'x\n' > "$repo/a/f.rs"
git -C "$repo" add -A >/dev/null 2>&1

bi_reason() {
  { printf '%s' "$BI_MIN_HEAD"
    printf '[bot-instructions.exclusions]\n[[bot-instructions.exclusions.path]]\nglob = "a/**"\nreason = "a generated%s tree"\n' "$1"
  } > "$repo/kendex.toml"
}
# Each control pins WHICH PREDICATE fired, not only the validator. This row
# carries `control` and `single-line` both, `apply` raises on the first to
# match, and `splitlines` inside `single-line` breaks on these same three
# characters — so a bare `expect_red toml-schema` passes whichever is doing
# the work. `apply` puts the predicate's name in the message.
for cp in u0085 u2028 u2029; do
  bi_reason ''
  expect_green "an ordinary [[bot-instructions.exclusions.path]] reason, the pair for \\$cp" \
    check --repo "$repo"
  bi_reason "\\$cp"
  expect_clause toml-schema '(control refusal, [[bot-instructions.exclusions.path]] reason)' \
    "a line separator \\$cp in [[bot-instructions.exclusions.path]] reason is the control predicate's refusal" \
    check --repo "$repo"
done

# `single-line`'s own clause, and the one character of it that carries weight.
# `splitlines` DROPS a trailing break, so the predicate appends a `.` before
# counting: without it `"a\n"` and `"a"` both read as one line and a reason
# ending in a newline passes.
bi_reason ''
expect_green 'an ordinary [[bot-instructions.exclusions.path]] reason, the pair below' check --repo "$repo"
{ printf '%s' "$BI_MIN_HEAD"
  printf '[bot-instructions.exclusions]\n[[bot-instructions.exclusions.path]]\nglob = "a/**"\nreason = "a generated tree\\n"\n'
} > "$repo/kendex.toml"
expect_clause toml-schema '(single-line refusal, [[bot-instructions.exclusions.path]] reason)' \
  'a [[bot-instructions.exclusions.path]] reason ending in a newline is the single-line predicate'"'"'s refusal' \
  check --repo "$repo"

# The same character in `[[bot-instructions.surface]] instructions`, which reaches
# `.coderabbit.yaml` inside a block scalar: the text after it would be emitted
# unindented, end the scalar, and leave PyYAML unable to read the file at all.
bi_surface() {
  { printf '%s' "$BI_MIN_HEAD"
    # A surface needs a route for its text, or `toml-schema` reds on the
    # surface set instead and the pair proves nothing about the separator.
    printf '[bot-instructions.bots]\ncodex = true\ncopilot = true\n'
    printf '[[bot-instructions.surface]]\nname = "tests"\nglobs = ["a/**"]\nreviewer_only = true\n'
    printf 'instructions = "An ordinary%s surface."\n' "$1"
  } > "$repo/kendex.toml"
}
# `render --dry-run`, like the empty-instructions control in
# `toml-schema.test.sh`: this pair needs a bot enabled for the surface text to
# have a route, and a fixture with bots on and no rendered outputs reds on
# `drift` under `check`.
bi_surface ''
bi_must_adopt --repo "$repo" || exit 1
expect_green 'an ordinary [[bot-instructions.surface]] instructions, the pair below' \
  render --dry-run --repo "$repo"
bi_surface '\u2028'
expect_clause toml-schema '(control refusal, [[bot-instructions.surface]] instructions)' \
  'a line separator in [[bot-instructions.surface]] instructions' \
  render --dry-run --repo "$repo"

bi_summary
